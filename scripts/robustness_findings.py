def family_adjusted(boot: sf.SceneBoot, rows: list[dict], bin_of: dict[str, int], nb: int):
    """Within-family standardised accuracy per bin: overall accuracy plus the bin's mean of
    (correct - the family's accuracy), with the family means recomputed in every scene draw."""
    fams = sorted({r["family"] for r in rows})
    fi = {f: k for k, f in enumerate(fams)}
    S, F = len(boot.scenes), len(fams)
    C = np.zeros((S, F, nb))
    N = np.zeros((S, F, nb))
    for r in rows:
        b = bin_of.get(r["task_id"])
        if b is None:
            continue
        s = boot.index[r["cluster"]]
        C[s, fi[r["family"]], b] += r["correct"]
        N[s, fi[r["family"]], b] += 1

    def stat(c: np.ndarray, n: np.ndarray) -> np.ndarray:
        # c, n: (..., F, nb)
        with np.errstate(invalid="ignore", divide="ignore"):
            fam_mean = c.sum(-1) / n.sum(-1)  # (..., F)
            fam_mean = np.nan_to_num(fam_mean)
            overall = c.sum((-1, -2)) / n.sum((-1, -2))
            resid = (c - fam_mean[..., None] * n).sum(-2)  # (..., nb)
            return overall[..., None] + resid / n.sum(-2)

    point = stat(C.sum(0), N.sum(0))
    W = boot.w
    draws = stat(
        np.einsum("bs,sfk->bfk", W, C, optimize=True),
        np.einsum("bs,sfk->bfk", W, N, optimize=True),
    )
    return point, draws


def fit_logit(rows: list[dict], cols: list[str], xfn) -> dict[str, Any]:
    """Logistic regression (IRLS) with scene-clustered standard errors."""
    X = np.array([xfn(r) for r in rows], dtype=float)
    y = np.array([float(r["correct"]) for r in rows])
    groups = [r["cluster"] for r in rows]
    beta, p, H, converged, iters = sf.irls(X, y)
    try:
        bread = np.linalg.inv(H)
    except np.linalg.LinAlgError:
        return {"stable": False, "reason": "singular information matrix"}
    resid = (y - p)[:, None] * X
    by: dict[str, np.ndarray] = defaultdict(lambda: np.zeros(X.shape[1]))
    for g, s in zip(groups, resid, strict=True):
        by[g] = by[g] + s
    G = len(by)
    meat = sum(np.outer(s, s) for s in by.values())
    V = bread @ meat @ bread * G / max(1, G - 1)
    se = np.sqrt(np.clip(np.diag(V), 0, None))
    stable = bool(converged and np.all(np.abs(beta) < 15) and np.all(np.isfinite(se)))
    terms = {}
    for j, c in enumerate(cols):
        b, s = float(beta[j]), float(se[j])
        terms[c] = {
            "log_odds": round(b, 4),
            "se": round(s, 4),
            "odds_ratio": round(math.exp(b), 3),
            "or_ci95": [round(math.exp(b - 1.96 * s), 3), round(math.exp(b + 1.96 * s), 3)],
        }
    return {"n": len(y), "scenes": G, "stable": stable, "iterations": iters, "terms": terms}


def axis_regression(rows: list[dict], tasks: dict, extra_models: list[str] | None = None):
    """correct ~ objects per 10 + hidden share per 25 points + camera level (vs clean) + family
    + camera rig (+ model), on every task with all three axes known."""
    keep = [
        r
        for r in rows
        if None not in (tasks[r["task_id"]]["n_objects"], tasks[r["task_id"]]["visible"])
        and tasks[r["task_id"]]["quality"] is not None
    ]
    fams = sorted({r["family"] for r in keep})
    cams = sorted({r["camera"] for r in keep})
    cols = ["intercept", "objects_per_10", "hidden_per_25pts", "camera_mild", "camera_harsh"]
    cols += ["camera_cctv"] + [f"family={f}" for f in fams[1:]] + [f"rig={c}" for c in cams[1:]]
    models = extra_models or []
    cols += [f"model={m}" for m in models[1:]]

    def x(r: dict) -> list[float]:
        t = tasks[r["task_id"]]
        q = t["quality"]
        out = [1.0, t["n_objects"] / 10, (1 - t["visible"]) / 0.25, q == 1, q == 2, q == 3]
        out += [r["family"] == f for f in fams[1:]] + [r["camera"] == c for c in cams[1:]]
        out += [r.get("model") == m for m in models[1:]]
        return out

    return fit_logit(keep, cols, x)


def breaking_point(boot: sf.SceneBoot, rows_by: dict[str, list[dict]], tasks: dict) -> dict:
    out: dict[str, Any] = {"axes": {}, "regression": {}, "chart": "../../media/breaking_point.png"}
    for ax in AXES:
        bin_of = {t: ax["fn"](i) for t, i in tasks.items()}
        nb = len(ax["bins"])
        entry: dict[str, Any] = {"title": ax["title"], "bins": ax["bins"], "models": {}}
        for key, rows in rows_by.items():
            raw = [
                sf.acc_stat(boot, rows, lambda r, b=b, bo=bin_of: bo.get(r["task_id"]) == b)
                for b in range(nb)
            ]
            adj_point, adj_draws = family_adjusted(boot, rows, bin_of, nb)
            used = [b for b in range(nb) if raw[b]["n"]]
            first, last = used[0], used[-1]
            # the hardest bin = the lowest family-adjusted accuracy
            worst = min(used, key=lambda b: adj_point[b])
            entry["models"][key] = {
                "raw": [
                    {k: v for k, v in s.items() if not k.startswith("_")} | {"bin": ax["bins"][b]}
                    for b, s in enumerate(raw)
                ],
                "adjusted": [
                    {
                        "bin": ax["bins"][b],
                        "accuracy": None if np.isnan(adj_point[b]) else round(adj_point[b], 4),
                        "ci95": sf.ci(adj_draws[:, b]),
                    }
                    for b in range(nb)
                ],
                # every bin against the easiest one (points), raw and family-adjusted
                "vs_first": {
                    ax["bins"][b]: {
                        "raw": round(raw[b]["accuracy"] - raw[first]["accuracy"], 4),
                        "raw_ci95": sf.ci(raw[b]["_draws"] - raw[first]["_draws"]),
                        "adjusted": round(float(adj_point[b] - adj_point[first]), 4),
                        "adjusted_ci95": sf.ci(adj_draws[:, b] - adj_draws[:, first]),
                    }
                    for b in used
                    if b != first
                },
                "last_minus_first": {
                    "from": ax["bins"][first],
                    "to": ax["bins"][last],
                    "raw": round(raw[last]["accuracy"] - raw[first]["accuracy"], 4),
                    "raw_ci95": sf.ci(raw[last]["_draws"] - raw[first]["_draws"]),
                    "adjusted": round(float(adj_point[last] - adj_point[first]), 4),
                    "adjusted_ci95": sf.ci(adj_draws[:, last] - adj_draws[:, first]),
                },
                "worst_minus_first": {
                    "from": ax["bins"][first],
                    "to": ax["bins"][worst],
                    "adjusted": round(float(adj_point[worst] - adj_point[first]), 4),
                    "adjusted_ci95": sf.ci(adj_draws[:, worst] - adj_draws[:, first]),
                },
                "max_raw_vs_adjusted_points": round(
                    float(
                        max(
                            abs(raw[b]["accuracy"] - adj_point[b])
                            for b in used
                            if not np.isnan(adj_point[b])
                        )
                    ),
                    4,
                ),
            }
        out["axes"][ax["key"]] = entry
    for key, rows in rows_by.items():
        out["regression"][key] = axis_regression(rows, tasks)
    pooled = [{**r, "model": k} for k, rows in rows_by.items() for r in rows]
    out["regression_pooled"] = axis_regression(pooled, tasks, list(rows_by))
    out["n_tasks"] = len(next(iter(rows_by.values())))
    return out


def moves(c: list[float] | None) -> bool | None:
    """True when a 95% interval of a change excludes zero."""
    if not c:
        return None
    return c[0] > 0 or c[1] < 0


def label_of(key: str) -> str:
    for k, name, effort in sf.MODELS:
        if k == key:
            return f"{name} {effort}"
    return key


COMPARE_TEXT = {
    ("objects", "21–25"): "21–25 objects on the table vs 2–5",
    ("visible", "under 60%"): "evidence under 60% visible vs fully visible",
    ("camera", "harsh"): "a harsh camera vs a clean one",
    ("camera", "CCTV"): "a CCTV camera vs a clean one",
}


def bp_verdicts(bp: dict) -> list[str]:
    summary, flat = [], []
    for ax in AXES:
        e = bp["axes"][ax["key"]]
        for hard in ax["report"]:
            ds = {k: m["vs_first"][hard] for k, m in e["models"].items() if hard in m["vs_first"]}
            if not ds:
                continue
            vals = sorted(-d["adjusted"] * 100 for d in ds.values())
            verb = "costs" if vals[0] >= 0 else "changes accuracy by"
            summary.append(
                f"{COMPARE_TEXT[(ax['key'], hard)]} {verb} {vals[0]:.0f} to {vals[-1]:.0f} points"
            )
            for k, d in ds.items():
                if not moves(d["adjusted_ci95"]):
                    c = d["adjusted_ci95"]
                    flat.append(
                        f"{COMPARE_TEXT[(ax['key'], hard)]} for {label_of(k)} "
                        f"({d['adjusted'] * 100:+.0f}, 95% CI {c[0] * 100:+.0f} to "
                        f"{c[1] * 100:+.0f})"
                    )
    lines = [
        "Breaking points (section 5): the difficulty controls move accuracy. Family-adjusted, "
        "against the easiest level, across the four settings: " + "; ".join(summary) + "."
    ]
    if flat:
        lines.append(
            "Where an axis does not detectably move accuracy (the 95% interval includes no "
            "change): " + "; ".join(flat) + "."
        )
    pooled = bp["regression_pooled"]
    if pooled.get("terms"):
        t = pooled["terms"]

        def orr(name: str) -> str:
            v = t[name]
            return f"{v['odds_ratio']:.2f} ({v['or_ci95'][0]:.2f} to {v['or_ci95'][1]:.2f})"

        flat_terms = [
            name
            for name in ("objects_per_10", "hidden_per_25pts", "camera_mild", "camera_harsh")
            + ("camera_cctv",)
            if t[name]["or_ci95"][0] <= 1 <= t[name]["or_ci95"][1]
        ]
        nice = {
            "objects_per_10": "10 more objects",
            "hidden_per_25pts": "25 points less of the evidence visible",
            "camera_mild": "mild camera",
            "camera_harsh": "harsh camera",
            "camera_cctv": "CCTV camera",
        }
        line = (
            "All three axes at once, family and camera rig held fixed (logistic regression over "
            f"all four settings, {pooled['n']} answers): odds of a right answer x"
            f"{orr('objects_per_10')} per 10 more objects, x{orr('hidden_per_25pts')} per 25 "
            f"points less visible, x{orr('camera_mild')} mild, x{orr('camera_harsh')} harsh, "
            f"x{orr('camera_cctv')} CCTV against a clean camera."
        )
        if flat_terms:
            line += " No detectable effect: " + ", ".join(nice[n] for n in flat_terms) + "."
        lines.append(line)
    return lines


