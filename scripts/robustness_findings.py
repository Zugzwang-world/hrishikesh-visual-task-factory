# --- 2. counterfactual twins ------------------------------------------------------------------


def twin_pairs(run: Path) -> list[dict[str, str]]:
    lay = RunLayout(run)
    pairs = []
    for row in manifest_rows(run):
        if "_twin_" not in row.scene_id:
            continue
        task = read_task(lay.root / row.path)
        if task.twin_of:
            pairs.append({"base": task.twin_of, "twin": row.task_id, "family": row.family})
    return pairs


def answers(run: Path, key: str) -> dict[str, dict]:
    out = {}
    for d in ("sweep", TWIN_DIR):
        path = run / d / key / "results.jsonl"
        if path.is_file():
            for r in read_jsonl(path):
                if r.get("error") != "no reply":
                    out.setdefault(r["task_id"], r)
    return out


def nouns_of(value: Any) -> set[str]:
    items = value if isinstance(value, list) else [value]
    out = set()
    for it in items:
        if isinstance(it, str) and it.strip():
            out.add(it.strip().lower().split()[-1])
    return out


def says(task: Any, truth: Any, raw: str) -> bool:
    """Does the reply give `truth` for this task (the eval scorer, in this task's view)?"""
    alt = task.model_copy(update={"answer": truth})
    try:
        return bool(score_task(alt, raw).correct)
    except ValueError:
        # `truth` names an object that is not nameable in this view: compare nouns
        got = score_task(task, raw)
        return got.parse_ok and nouns_of(got.parsed) == nouns_of(truth)


def twin_flip(run: Path, models: list[str]) -> dict[str, Any]:
    lay = RunLayout(run)
    rows = {r.task_id: r for r in manifest_rows(run)}
    pairs = twin_pairs(run)
    tasks = {}
    for p in pairs:
        for t in (p["base"], p["twin"]):
            tasks[t] = read_task(lay.root / rows[t].path)
    per_model: dict[str, list[dict]] = {}
    for key in models:
        ans = answers(run, key)
        out = []
        for p in pairs:
            a, b = ans.get(p["base"]), ans.get(p["twin"])
            if a is None or b is None:
                continue
            base, twin = tasks[p["base"]], tasks[p["twin"]]
            a_ok, b_ok = bool(a["correct"]), bool(b["correct"])
            b_old = (not b_ok) and b["parse_ok"] and says(twin, base.answer, b["raw_response"])
            cat = (
                "both_right"
                if a_ok and b_ok
                else "twin_only"
                if b_ok
                else "sticks"
                if b_old
                else "other"
            )
            out.append(
                {
                    "base": p["base"],
                    "twin": p["twin"],
                    "family": p["family"],
                    "yes_no": twin.answer_type == "bool",
                    "cluster": rows[p["base"]].scene_id.split("_twin_")[0],
                    "a_ok": a_ok,
                    "b_ok": b_ok,
                    "cat": cat,
                    "base_answer": a.get("parsed"),
                    "twin_answer": b.get("parsed"),
                }
            )
        per_model[key] = out
    scenes = sorted({r["cluster"] for rs in per_model.values() for r in rs})
    boot = sf.SceneBoot(scenes, seed=sf.SEED + 7)

    def share(rs: list[dict], hit, mask=lambda r: True) -> dict[str, Any]:
        num = boot.sums(rs, lambda r: hit(r), mask)
        den = boot.sums(rs, lambda r: 1, mask)
        point, draws = boot.ratio(num, den)
        return {
            "n": int(den.sum()),
            "k": int(num.sum()),
            "share": None if point is None else round(float(point), 4),
            "ci95": sf.ci(draws),
            "_draws": draws,
        }

    res: dict[str, Any] = {
        "pairs_total": len(pairs),
        "scenes": len(scenes),
        "chart": "../../media/twin_flip.png",
        "models": {},
    }
    for key, rs in per_model.items():
        m: dict[str, Any] = {"pairs": len(rs)}
        for cat in ("both_right", "twin_only", "sticks", "other"):
            m[cat] = share(rs, lambda r, c=cat: r["cat"] == c)
        m["follows_flip"] = share(rs, lambda r: r["b_ok"])
        m["original_right"] = share(rs, lambda r: r["a_ok"])
        m["given_original_right"] = {
            "follows": share(rs, lambda r: r["b_ok"], lambda r: r["a_ok"]),
            "sticks": share(rs, lambda r: r["cat"] == "sticks", lambda r: r["a_ok"]),
        }
        m["sticks_share_of_twin_misses"] = {
            "yes_no": share(
                rs, lambda r: r["cat"] == "sticks", lambda r: not r["b_ok"] and r["yes_no"]
            ),
            "other_types": share(
                rs, lambda r: r["cat"] == "sticks", lambda r: not r["b_ok"] and not r["yes_no"]
            ),
        }
        fams = sorted({r["family"] for r in rs})
        m["by_family"] = {
            f: {
                "pairs": sum(r["family"] == f for r in rs),
                **{
                    c: sum(r["family"] == f and r["cat"] == c for r in rs)
                    for c in ("both_right", "twin_only", "sticks", "other")
                },
            }
            for f in fams
        }
        res["models"][key] = m
    keys = list(per_model)
    comps = {}
    for a, b in (
        ("claude-opus-5-5-xhigh", "claude-opus-5-5"),
        ("claude-opus-5-5", "claude-haiku-5-5"),
    ):
        if a in res["models"] and b in res["models"]:
            da, db = res["models"][a]["both_right"], res["models"][b]["both_right"]
            comps[f"{a} vs {b}"] = {
                "both_right_change": round(da["share"] - db["share"], 4),
                "ci95": sf.ci(da["_draws"] - db["_draws"]),
            }
    res["comparisons"] = comps
    res["examples"] = {k: per_model[k] for k in keys}  # kept in memory for the risk cards
    return res


def twin_verdicts(tf: dict) -> list[str]:
    ms = tf["models"]
    if not ms:
        return []
    n = min(m["pairs"] for m in ms.values())

    def pc(s: dict) -> str:
        c = s["ci95"]
        return f"{s['share'] * 100:.0f}%" + (
            f" ({c[0] * 100:.0f} to {c[1] * 100:.0f})" if c else ""
        )

    parts = [
        f"{label_of(k)} {pc(m['both_right'])} both right, {pc(m['sticks'])} stuck to the old answer"
        for k, m in ms.items()
    ]
    lines = [
        f"Counterfactual twins ({n} G6 pairs per model: one object moved, so the true answer "
        "changed): " + "; ".join(parts) + "."
    ]
    cond = [
        f"{label_of(k)} {m['given_original_right']['follows']['share'] * 100:.0f}% follow, "
        f"{m['given_original_right']['sticks']['share'] * 100:.0f}% stick"
        for k, m in ms.items()
    ]
    lines.append(
        "When a model got the original right, how often its twin answer follows the change vs "
        "repeats the old answer: " + "; ".join(cond) + "."
    )
    return lines


