def twin_cost(run: Path) -> dict[str, Any] | None:
    path = run / TWIN_DIR / "costs.json"
    if not path.is_file():
        return None
    c = json.loads(path.read_text())
    models = {k: round(v["cost_usd"], 2) for k, v in c["models"].items()}
    return {
        "tasks": c["n_tasks"],
        "answers": sum(v["replies"] for v in c["models"].values()),
        "models": models,
        "total_usd": round(sum(v["cost_usd"] for v in c["models"].values()), 2),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--out", default="docs/reports/v1")
    ap.add_argument("--media", default="docs/media")
    args = ap.parse_args()
    run = Path(args.run).resolve()
    out_dir, media = Path(args.out), Path(args.media)
    ids = json.loads((run / "sweep" / "task_set.json").read_text())["task_ids"]
    tasks = sf.load_tasks(run, ids)
    rows_by = {k: rows for k, _, _ in sf.MODELS if (rows := sf.load_model(run, k, tasks))}
    common = set.intersection(*(set(r["task_id"] for r in rs) for rs in rows_by.values()))
    rows_by = {k: [r for r in rs if r["task_id"] in common] for k, rs in rows_by.items()}
    boot = sf.SceneBoot(sorted({t["cluster"] for t in tasks.values()}))

    bp = breaking_point(boot, rows_by, tasks)
    tf = twin_flip(run, list(rows_by))
    tf.pop("examples", None)
    tf["cost"] = twin_cost(run)
    findings_path = out_dir / "findings.json"
    findings = json.loads(findings_path.read_text())
    cards = risk_cards(run, rows_by, tasks, bp, tf, findings, media)

    findings["breaking_point"] = sf.strip(bp)
    findings["twin_flip"] = sf.strip(tf)
    findings["risk_cards"] = cards
    findings["verdicts_robustness"] = bp_verdicts(bp) + twin_verdicts(tf)
    findings_path.write_text(json.dumps(findings, indent=2) + "\n")
    chart_rel = "../../media/shortcut_conflict_accuracy.png"
    (out_dir / "findings.md").write_text(sf.markdown(findings, run, chart_rel))
    (out_dir / "risk_cards.md").write_text(risk_cards_md(cards, len(common)))
    bp_chart(bp, media / "breaking_point.png", len(common))
    if tf["models"]:
        twin_chart(tf, media / "twin_flip.png")
    for v in findings["verdicts_robustness"]:
        print("-", v)
    print(json.dumps({k: c["numbers"] for k, c in cards.items()}, indent=1))


if __name__ == "__main__":
    main()
