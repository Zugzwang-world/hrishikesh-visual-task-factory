# Names a model may use for a real object that the scorer's vocabulary lacks: these are not
# counted as objects outside the scene (found in the v1 answers; the scorer still marks them
# wrong: 2 to 11 answers per model, at most 0.7 points of accuracy).
NOT_INVENTED = {
    "stone": {"rock"},
    "pebble": {"rock"},
    "pitcher": {"jug"},
    "ball": {"baseball"},
    "animal": {"elephant", "duck"},
    "figurine": {"elephant", "duck"},
    "toy": {"elephant", "duck"},
}
_scene_cache: dict[str, list[dict]] = {}


def scene_categories(run: Path, scene_id: str) -> set[str]:
    if scene_id not in _scene_cache:
        folder = run / ("twins" if "_twin_" in scene_id else "scenes") / scene_id
        path = folder / "render" / "scene.settled.json"
        _scene_cache[scene_id] = json.loads(path.read_text())["objects"]
    return {o["category"] for o in _scene_cache[scene_id]}


def invented_item(item: Any, cats: set[str]) -> bool | None:
    """True when a named item is no object in the scene (any camera); None if it names none."""
    if not isinstance(item, str) or not item.strip():
        return None
    words = parse_name_words(item, extra_nouns=cats)
    if words.table or words.none:
        return False
    toks = re.findall(r"[a-z]+", item.lower())
    if any(NOT_INVENTED.get(t.rstrip("s"), set()) & cats for t in toks):
        return False
    if words.nouns:
        return not any(noun_matches(n, c, cats) for n in words.nouns for c in cats)
    if not toks:
        return None
    head = toks[-1][:-1] if toks[-1].endswith("s") and len(toks[-1]) > 3 else toks[-1]
    return head not in cats  # a noun the factory never uses: no such object in the scene


def error_types(run: Path, rows: list[dict], tasks: dict, raw: dict[str, dict]) -> list[dict]:
    """Per answer, the rule-based error types."""
    out = []
    for r in rows:
        info = tasks[r["task_id"]]
        task = info["task"]
        rec = raw[r["task_id"]]
        e = {"task_id": r["task_id"], "correct": r["correct"], "family": r["family"]}
        e["shortcut"] = bool(r["shortcut"])
        e["conflict"] = r["conflict"] is True
        e["invented"] = None
        if task.answer_type in ("object", "set") and not r["correct"]:
            val = extract_answer(rec["raw_response"])
            items = [val] if task.answer_type == "object" else (split_items(val) or [])
            cats = scene_categories(run, info["scene_id"])
            flags = [invented_item(it, cats) for it in items]
            e["invented"] = any(f for f in flags if f)
        e["object_answer"] = task.answer_type in ("object", "set")
        e["single_object"] = task.answer_type == "object"
        e["count"] = task.family in ("count", "count_attribute")
        e["off_by_one"] = False
        if e["count"] and r["parse_ok"] and not r["correct"]:
            try:
                e["off_by_one"] = abs(int(r["parsed"]) - int(task.answer)) == 1
            except (TypeError, ValueError):
                pass
        e["unparseable"] = not r["parse_ok"]
        out.append(e)
    return out


def risk_numbers(errs: list[dict]) -> dict[str, Any]:
    conflict = [e for e in errs if e["conflict"]]
    obj = [e for e in errs if e["object_answer"]]
    cnt = [e for e in errs if e["count"]]
    return {
        "shortcut": {"k": sum(e["shortcut"] for e in conflict), "n": len(conflict)},
        "invented": {
            "k": sum(bool(e["invented"]) for e in obj),
            "n": len(obj),
            "misses": sum(not e["correct"] for e in obj),
        },
        "off_by_one": {
            "k": sum(e["off_by_one"] for e in cnt),
            "n": len(cnt),
            "misses": sum(not e["correct"] for e in cnt),
        },
        "unparseable": {"k": sum(e["unparseable"] for e in errs), "n": len(errs)},
    }


def severity(rate: float) -> str:
    return "high" if rate >= 0.2 else "medium" if rate >= 0.05 else "low"


def pick_examples(
    key: str, errs: list[dict], tasks: dict, raw: dict, used: set[str]
) -> list[dict[str, Any]]:
    """Two examples per model: a nearest-to-gripper shortcut pick (else any shortcut pick) and
    an invented object (else a count off by one); deterministic, no task used twice."""

    def first(pred) -> dict | None:
        for e in sorted(errs, key=lambda e: e["task_id"]):
            if e["task_id"] not in used and pred(e):
                return e
        return None

    picks = []
    for _kind, preds in (
        (
            "shortcut",
            [
                lambda e: e["shortcut"] and e["family"] == "nearest_to_gripper",
                lambda e: e["shortcut"],
            ],
        ),
        (
            "invented",
            [
                lambda e: e["invented"] and e["single_object"],
                lambda e: e["invented"],
                lambda e: e["off_by_one"],
            ],
        ),
    ):
        for pred in preds:
            e = first(pred)
            if e:
                used.add(e["task_id"])
                t = tasks[e["task_id"]]["task"]
                rec = raw[e["task_id"]]
                val = extract_answer(rec["raw_response"])
                picks.append(
                    {
                        "kind": "shortcut"
                        if e["shortcut"]
                        else "invented"
                        if e["invented"]
                        else "off_by_one",
                        "task_id": e["task_id"],
                        "scene_id": tasks[e["task_id"]]["scene_id"],
                        "camera": t.camera_id,
                        "family": t.family,
                        "question": t.question,
                        "truth": t.answer_text,
                        "shortcut_answer": t.shortcut_answer,
                        "model_answer": val if isinstance(val, str | int | float | list) else None,
                    }
                )
                break
    return picks


def save_example_image(run: Path, task_id: str, out: Path, width: int = 420) -> None:
    from PIL import Image

    rows = {r.task_id: r for r in manifest_rows(run)}
    src = RunLayout(run).root / Path(rows[task_id].path).parent / "image.png"
    img = Image.open(src).convert("RGB")
    h = round(img.height * width / img.width)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.resize((width, h), Image.LANCZOS).save(out, "JPEG", quality=72, optimize=True)


def trigger_conditions(bp: dict, key: str, families: dict[str, dict]) -> list[str]:
    """The two difficulty bins with the largest family-adjusted drop, plus the two weakest
    families of this model."""
    drops = []
    for ax in AXES:
        m = bp["axes"][ax["key"]]["models"][key]
        d = m["worst_minus_first"]
        if d["adjusted_ci95"] and d["adjusted_ci95"][1] < 0:
            drops.append(
                (
                    d["adjusted"],
                    f"{ax['title'].lower()}: {d['to']} ({d['adjusted'] * 100:+.0f} pts)",
                )
            )
    drops.sort()
    weak = sorted(
        ((s["accuracy"], f) for f, s in families.items() if s.get("n", 0) >= 30),
    )[:2]
    out = ["2D shortcut conflicts with the 3D truth"]
    out += [txt for _, txt in drops[:2]]
    out += [f"{sf.fam(f)} questions ({a * 100:.0f}% right)" for a, f in weak]
    return out


def mitigation(key: str, nums: dict, fm: dict, findings: dict) -> str:
    """One mitigation idea per model setting, worded from its own numbers."""
    fams = (fm.get("acc") or {}).get("by_family", {})
    if key == "claude-haiku-5-5":
        best = max(
            (m["acc"]["by_family"].get("count_attribute", {}).get("accuracy") or 0)
            for m in findings.get("models", {}).values()
        )
        own = fams.get("count_attribute", {}).get("accuracy") or 0
        return (
            "Keep it off spatial decisions: its misses are scattered rather than pulled to the "
            f"shortcut (capture {fm.get('capture', {}).get('ratio')}x chance), so no single "
            "check fixes them. Use it for colour counts, where it is close to the best setting "
            f"({own * 100:.0f}% vs {best * 100:.0f}%); route nearest, relation and distance "
            "questions to a larger model or to depth geometry."
        )
    if key == "claude-sonnet-5-5":
        c = (fm.get("capture_by_family") or {}).get("nearest_to_gripper") or {}
        return (
            "Check every 'which object is nearest the gripper' answer against depth (a depth "
            "camera or a second view) before the gripper moves: "
            f"{c.get('shortcut_picks')} of its {c.get('answered_misses')} misses there name the "
            "object nearest in the image."
        )
    if key == "claude-opus-5-5":
        inv = nums["invented"]
        return (
            "Give it the cell's object list with the image (a real workcell knows its "
            f"inventory): {inv['k'] / max(1, inv['misses']) * 100:.0f}% of its wrong object "
            "answers name an object that is not on the table, mostly a real object "
            "misidentified (the pot called a bowl, the can a jar)."
        )
    if key == "claude-opus-5-5-xhigh":
        comp = (findings.get("comparisons") or {}).get(
            "claude-opus-5-5-xhigh vs claude-opus-5-5", {}
        )
        th = fm.get("mean_thinking_tokens", {}).get("conflict", {}).get("mean")
        hi = (
            findings.get("models", {})
            .get("claude-opus-5-5", {})
            .get("mean_thinking_tokens", {})
            .get("conflict", {})
            .get("mean")
        )
        return (
            "Do not pay for xhigh on spatial picks: on conflict tasks it thinks "
            f"{th:.0f} vs {hi:.0f} tokens at high, and the shortcut gap moves by "
            f"{comp.get('gap_change_points', 0) * 100:+.0f} points. Spend the budget on "
            "sensing (depth, a second view) instead."
            if th and hi
            else "Spend on sensing (depth, a second view), not on more thinking."
        )
    return ""


def risk_cards(
    run: Path, rows_by: dict, tasks: dict, bp: dict, tf: dict, findings: dict, media: Path
) -> dict[str, Any]:
    cards: dict[str, Any] = {}
    used: set[str] = set()
    for key, rows in rows_by.items():
        raw = {r["task_id"]: r for r in read_jsonl(run / "sweep" / key / "results.jsonl")}
        errs = error_types(run, rows, tasks, raw)
        nums = risk_numbers(errs)
        fm = (findings.get("models") or {}).get(key, {})
        fams = (fm.get("acc") or {}).get("by_family", {})
        ex = pick_examples(key, errs, tasks, raw, used)
        for i, e in enumerate(ex, 1):
            name = f"{key}_{i}.jpg"
            save_example_image(run, e["task_id"], media / "risk_cards" / name)
            e["image"] = f"../../media/risk_cards/{name}"
        sh, inv, ob = nums["shortcut"], nums["invented"], nums["off_by_one"]
        twin = tf["models"].get(key, {})
        cards[key] = {
            "label": label_of(key),
            "overall": (fm.get("acc") or {}).get("overall", {}).get("accuracy"),
            "numbers": nums,
            "severity": {
                "shortcut": severity(sh["k"] / sh["n"]) if sh["n"] else None,
                "invented": severity(inv["k"] / inv["n"]) if inv["n"] else None,
                "off_by_one": severity(ob["k"] / ob["n"]) if ob["n"] else None,
            },
            "triggers": trigger_conditions(bp, key, fams),
            "twin_sticks": (twin.get("sticks") or {}).get("share"),
            "twin_both_right": (twin.get("both_right") or {}).get("share"),
            "capture_ratio": (fm.get("capture") or {}).get("ratio"),
            "examples": ex,
            "mitigation": mitigation(key, nums, fm, findings),
        }
    return cards


def risk_cards_md(cards: dict, n_tasks: int) -> str:
    keys = list(cards)
    head = "| | " + " | ".join(f"**{cards[k]['label']}**" for k in keys) + " |"
    sep = "| --- | " + " | ".join("---" for _ in keys) + " |"

    def row(name: str, fn) -> str:
        return f"| **{name}** | " + " | ".join(fn(cards[k]) for k in keys) + " |"

    def rate(x: dict) -> str:
        return f"{x['k'] / x['n'] * 100:.0f}% ({x['k']} of {x['n']})" if x["n"] else "–"

    def share_of_misses(x: dict) -> str:
        return f"{x['k'] / max(1, x['misses']) * 100:.0f}%"

    def top_risk(c: dict) -> str:
        return (
            "Answers from the 2D picture, not the 3D scene: picks the object that looks "
            "nearest or lowest in the image"
            if (c["capture_ratio"] or 0) > 1.1
            else "Unreliable spatial reading: wrong on 2D-shortcut conflicts, but its misses "
            "are spread rather than pulled to the shortcut"
        )

    def ex_cell(c: dict, i: int) -> str:
        if len(c["examples"]) < i:
            return "–"
        e = c["examples"][i - 1]
        ans = e["model_answer"]
        ans = ", ".join(map(str, ans)) if isinstance(ans, list) else ans
        kind = {
            "shortcut": "shortcut answer",
            "invented": "object not in the scene",
            "off_by_one": "count off by one",
        }[e["kind"]]
        return (
            f"![{e['task_id']}]({e['image']})<br>*{kind}* · {e['camera']} camera<br>"
            f"Q: {e['question']}<br>Truth: **{e['truth']}** · Model: **{ans}**"
            + (
                f" · 2D shortcut: {e['shortcut_answer']}"
                if e["kind"] == "shortcut" and e["shortcut_answer"]
                else ""
            )
        )

    lines = [
        "# Risk cards: Claude models on robot-workcell spatial questions",
        "",
        "One column per model setting we tested, from frozen dataset v1 (300 scenes, 3,181 "
        f"tasks; every model answered the same {n_tasks} tasks with only the image and the "
        "question). Error types are counted by rules over the answers, not by hand. These "
        "cards speak only about the Claude models we tested.",
        "",
        head,
        sep,
        row(
            "Overall accuracy",
            lambda c: f"{c['overall'] * 100:.0f}%" if c["overall"] is not None else "–",
        ),
        row("Risk", top_risk),
        row(
            "Severity",
            lambda c: (
                f"{c['severity']['shortcut']} (shortcut), {c['severity']['invented']} "
                f"(object not in the scene), {c['severity']['off_by_one']} (count off by one)"
            ),
        ),
        row("Trigger conditions", lambda c: "; ".join(c["triggers"])),
        row(
            "Error type: 2D-shortcut answer (of conflict tasks)",
            lambda c: rate(c["numbers"]["shortcut"]),
        ),
        row(
            "Error type: names an object not in the scene (of object answers)",
            lambda c: (
                rate(c["numbers"]["invented"])
                + f"; {share_of_misses(c['numbers']['invented'])} of its wrong object answers"
            ),
        ),
        row(
            "Error type: count off by one (of count tasks)",
            lambda c: (
                rate(c["numbers"]["off_by_one"])
                + f"; {c['numbers']['off_by_one']['k']} of {c['numbers']['off_by_one']['misses']} "
                "count misses"
            ),
        ),
        row(
            "Counterfactual twin: sticks to the old answer",
            lambda c: (
                f"{c['twin_sticks'] * 100:.0f}% of pairs (both right "
                f"{c['twin_both_right'] * 100:.0f}%)"
                if c["twin_sticks"] is not None
                else "–"
            ),
        ),
        row("Example 1", lambda c: ex_cell(c, 1)),
        row("Example 2", lambda c: ex_cell(c, 2)),
        row("Mitigation", lambda c: c["mitigation"]),
        "",
        "**How the rules work.** *2D-shortcut answer*: on a task where a flat 2D heuristic "
        "(nearest in the image, lowest in the frame) disagrees with the 3D truth, the answer "
        "equals the heuristic's answer (the eval scorer, against the task's shortcut_answer). "
        "*Names an object not in the scene*: a wrong object or list answer names a kind of "
        "object that is nowhere in the scene file (all cameras, not only the visible ones); "
        "most are real objects misidentified (the pot called a bowl, the can a jar, the kiwi a "
        "potato), which a rule cannot tell from a pure invention; a few true synonyms the "
        "scorer lacks (stone, pitcher, ball for a baseball, toy animal) are not counted. "
        "*Count off by one*: a count answer exactly one away from the truth. *Severity*: each "
        "of these errors sends a gripper to the wrong object or acts on a wrong count, so "
        "severity follows frequency: high when the error hits at least 20% of the tasks at "
        "risk, medium from 5%, low below. *Trigger conditions*: the "
        "difficulty levels with the largest family-adjusted drop "
        "([breaking points](findings.md#5-breaking-points)) and the model's two weakest "
        "families. *Sticks to the old answer*: on a "
        "[G6 twin](findings.md#6-counterfactual-twins), the model gives the answer that was "
        "true before the object moved.",
        "",
        "Generated by `scripts/robustness_findings.py`; numbers in findings.json (risk_cards).",
        "",
    ]
    return "\n".join(lines)


