def objects_bin(i: dict) -> int | None:
    n = i["n_objects"]
    return None if n is None else min(4, max(0, (int(n) - 1) // 5))  # 2-5, 6-10, ..., 21-25


def visible_bin(i: dict) -> int | None:
    v = i["visible"]
    if v is None:
        return None
    return 0 if v >= 0.9999 else 1 if v >= 0.8 else 2 if v >= 0.6 else 3


def camera_bin(i: dict) -> int | None:
    return i["quality"]


