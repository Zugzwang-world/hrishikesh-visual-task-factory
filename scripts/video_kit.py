def load(n: dict | None = None) -> tuple[list[dict], dict]:
    n = numbers() if n is None else n
    edit = yaml.safe_load(EDIT.read_text())
    ending = {ENDING_REAL: "real", ENDING_GAP: "gap"}.get(n.get("SIM2REAL_ENDING") or "")

    def fill(text: str) -> str:
        return re.sub(r"\{\{([A-Z0-9_]+)\}\}", lambda m: n.get(m.group(1)) or m.group(0), text)

    shots = []
    for s in edit["shots"]:
        s = dict(s)
        if "say_by_ending" in s:
            s["say"] = s["say_by_ending"][ending] if ending else "{{SIM2REAL_ENDING}}"
            s["endings"] = {k: fill(v) for k, v in s["say_by_ending"].items()}
        if s.get("say"):
            s["say"] = fill(" ".join(s["say"].split()))
        if s.get("card"):
            s["card"] = {k: (fill(v) if isinstance(v, str) else [fill(x) for x in v]) for k, v in s["card"].items()}
        shots.append(s)
    return shots, edit


def timecodes(shots: list[dict], key: str = "seconds") -> list[float]:
    t, out = 0.0, []
    for s in shots:
        out.append(t)
        t += float(s[key])
    out.append(t)
    return out


def mmss(t: float) -> str:
    return f"{int(t // 60)}:{int(t % 60):02d}"


def placeholders_in(text: str) -> list[str]:
    return re.findall(r"\{\{[A-Z0-9_]+\}\}", text or "")


