def md_to_html(md: str, title: str) -> str:
    """Just enough Markdown for the shot list: headings, lists, tables, bold, code, links."""

    def inline(t: str) -> str:
        t = html.escape(t)
        t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
        t = re.sub(r"`(.+?)`", r"<code>\1</code>", t)
        return re.sub(r"\[(.+?)\]\((.+?)\)", r"\1", t)

    out, in_table, in_list = [], False, None
    for line in md.splitlines():
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if set("".join(cells)) <= set("- "):
                continue
            if not in_table:
                out.append("<table><tr>" + "".join(f"<th>{inline(c)}</th>" for c in cells) + "</tr>")
                in_table = True
            else:
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        m = re.match(r"^(\s*)(\d+\.|-) (.*)", line)
        if m:
            tag = "ol" if m.group(2)[0].isdigit() else "ul"
            if in_list != tag:
                if in_list:
                    out.append(f"</{in_list}>")
                start = f' start="{m.group(2)[:-1]}"' if tag == "ol" else ""
                out.append(f"<{tag}{start}>")
                in_list = tag
            out.append(f"<li>{inline(m.group(3))}</li>")
            continue
        if in_list and line.strip():
            out.append(f"</{in_list}>")
            in_list = None
        if line.startswith("#"):
            level = len(line) - len(line.lstrip("#"))
            out.append(f"<h{level}>{inline(line.lstrip('#').strip())}</h{level}>")
        elif line.strip():
            out.append(f"<p>{inline(line)}</p>")
    if in_table:
        out.append("</table>")
    if in_list:
        out.append(f"</{in_list}>")
    css = ("body{font-family:'Avenir Next',Helvetica,Arial,sans-serif;font-size:10.5pt;color:#0f1016;margin:0}"
           "h1{font-size:20pt;margin:0 0 6pt}h2{font-size:13pt;color:#176eb8;margin:14pt 0 4pt}"
           "table{border-collapse:collapse;width:100%;margin:4pt 0}th,td{border:1px solid #d9dee5;padding:4pt 5pt;"
           "vertical-align:top;text-align:left;font-size:9pt}th{background:#f2f4f7}code{font-size:9pt}"
           "li{margin:2pt 0}p{margin:4pt 0}")  # fmt: skip
    return f"<!doctype html><html><head><meta charset='utf-8'><title>{title}</title><style>{css}</style></head><body>{''.join(out)}</body></html>"


def print_pdf(html_text: str, pdf: Path) -> None:
    from playwright.sync_api import sync_playwright

    tmp = WORK / "shot_list.html"
    tmp.parent.mkdir(parents=True, exist_ok=True)
    tmp.write_text(html_text, encoding="utf-8")
    with sync_playwright() as p:
        try:
            browser = p.chromium.launch()
        except Exception:
            browser = p.chromium.launch(channel="chrome")
        page = browser.new_page()
        page.goto(tmp.as_uri())
        page.pdf(path=str(pdf), format="A4", landscape=True, print_background=True,
                 margin={"top": "14mm", "bottom": "14mm", "left": "12mm", "right": "12mm"})  # fmt: skip
        browser.close()


def srt_time(t: float) -> str:
    ms = round(t * 1000)
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def caption_events(shots: list[dict], starts: list[float], key: str = "seconds") -> list[tuple[float, float, str]]:
    """Each shot's words split into sentences, timed in proportion to their length."""
    events = []
    for s, t0 in zip(shots, starts, strict=False):
        say = s.get("say")
        if not say:
            continue
        dur = float(s[key])
        parts = [p.strip() for p in re.split(r"(?<=[.?!:])\s+(?=[A-Z{])", say) if p.strip()]
        merged: list[str] = []
        for p in parts:  # keep a caption to at most two short lines
            if merged and len(merged[-1]) + len(p) < 70:
                merged[-1] += " " + p
            else:
                merged.append(p)
        total = sum(len(p) for p in merged)
        a, span = t0 + 0.25, max(0.5, dur - 0.5)
        for p in merged:
            b = a + span * len(p) / total
            events.append((a, b, p))
            a = b
    return events


def write_srt(events: list[tuple[float, float, str]], path: Path) -> None:
    rows = [f"{i}\n{srt_time(a)} --> {srt_time(b)}\n{text}\n" for i, (a, b, text) in enumerate(events, 1)]
    path.write_text("\n".join(rows), encoding="utf-8")


def write_ass(events: list[tuple[float, float, str]], path: Path) -> None:
    def ts(t: float) -> str:
        cs = round(t * 100)
        return f"{cs // 360000}:{cs // 6000 % 60:02d}:{cs // 100 % 60:02d}.{cs % 100:02d}"

    head = (
        "[Script Info]\nScriptType: v4.00+\nPlayResX: 1920\nPlayResY: 1080\nWrapStyle: 0\nScaledBorderAndShadow: yes\n\n"
        "[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
        "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
        "Alignment, MarginL, MarginR, MarginV, Encoding\n"
        "Style: Cap,Avenir Next Demi Bold,46,&H00FFFFFF,&H00FFFFFF,&H64000000,&H64000000,0,0,0,0,100,100,0,0,3,14,0,2,220,220,56,1\n\n"
        "[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    )  # fmt: skip
    body = "".join(f"Dialogue: 0,{ts(a)},{ts(b)},Cap,,0,0,0,,{text.replace(chr(10), ' ')}\n" for a, b, text in events)
    path.write_text(head + body, encoding="utf-8")


