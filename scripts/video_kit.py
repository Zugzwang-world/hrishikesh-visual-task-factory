"""The demo video kit from one edit list (brief VTF-09, section 3): docs/video/edit.yaml.

    uv run scripts/video_kit.py docs                  # script.md, shot_list.md and .pdf, captions.srt
    uv run scripts/video_kit.py plan [--placeholders] # out/video/plan.tsv, cards, captions (make_video.sh)

`docs` writes what the founder reads and the captions file, with every {{KEY}} filled from
scripts/demo_numbers.py where its number exists. `plan` is the first half of
scripts/make_video.sh: it matches the founder's clips in video/inbox/ to the desk shots and
voice-overs, measures every piece, stretches a shot whose voice-over runs long, draws the title
cards and placeholder slates, and times the burnt-in captions. make_video.sh then does the
ffmpeg work.

Inbox matching (the founder does no clerical work, so names are optional):
  * a file named after a shot (D1.mov, S5.m4a, VO_S5.wav) goes to that shot;
  * other video clips go to the desk shots D1..D4 in recording order (creation time);
  * other audio files go to the voice-over shots in order; one long audio file with a pause of
    about two seconds between lines is split at its longest pauses.
"""

