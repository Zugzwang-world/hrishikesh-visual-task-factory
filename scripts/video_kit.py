def probe(path: Path) -> dict:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                          "format=duration:format_tags=creation_time:stream=codec_type",
                          "-of", "json", str(path)], capture_output=True, text=True)  # fmt: skip
    if out.returncode:
        return {}
    j = json.loads(out.stdout or "{}")
    kinds = {s.get("codec_type") for s in j.get("streams", [])}
    fmt = j.get("format", {})
    return {
        "duration": float(fmt.get("duration") or 0),
        "video": "video" in kinds,
        "audio": "audio" in kinds,
        "created": (fmt.get("tags") or {}).get("creation_time") or f"{path.stat().st_mtime:020.6f}",
    }


def font(size: int, face: int = MEDIUM) -> ImageFont.FreeTypeFont:
    try:
        return ImageFont.truetype(FONT, size, index=face)
    except OSError:
        return ImageFont.load_default(size)


def draw_card(card: dict, out: Path, slate: str | None = None) -> None:
    img = Image.new("RGB", (W, H), (15, 16, 22))
    d = ImageDraw.Draw(img)
    for x in range(W):  # the template's foot bar, blue to orange
        f = x / (W - 1)
        d.line([(x, H - 22), (x, H)], fill=(round(23 + f * (220 - 23)), round(110 + f * (131 - 110)), round(184 + f * (53 - 184))))
    y = 330 if card.get("lines") else 400
    title = card.get("title", "")
    tf = font(104 if len(title) < 28 else 76, DEMI)
    ph = bool(placeholders_in(title))
    d.text((160, y), title, font=tf, fill=(217, 59, 0) if ph else (255, 255, 255))
    y += 150
    if card.get("subtitle"):
        sub, f = card["subtitle"], font(54 if not slate else 40, MEDIUM)
        rows, line = [], ""
        for word in sub.split():  # wrap to the card width
            trial = f"{line} {word}".strip()
            if d.textlength(trial, font=f) > W - 330 and line:
                rows.append(line)
                line = word
            else:
                line = trial
        rows.append(line)
        for row in rows[:4]:
            d.text((164, y), row, font=f, fill=(220, 131, 53) if not slate else (200, 204, 212))
            y += 72 if not slate else 56
        y += 30
    for line in card.get("lines", []):
        d.text((164, y), line, font=font(44, REGULAR), fill=(220, 224, 232))
        y += 66
    if card.get("foot") and not slate:
        d.text((164, H - 120), card["foot"], font=font(32, REGULAR), fill=(150, 156, 168))
    if slate:
        d.rounded_rectangle((150, 150, 690, 220), radius=12, fill=(217, 59, 0))
        d.text((172, 160), slate, font=font(40, DEMI), fill=(255, 255, 255))
    img.save(out)


def split_long_vo(path: Path, n_parts: int, work: Path) -> list[Path]:
    """One voice memo with every line: cut at its n_parts - 1 longest pauses."""
    out = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-af", "silencedetect=noise=-35dB:d=0.7",
                          "-f", "null", "-"], capture_output=True, text=True)  # fmt: skip
    starts = [float(x) for x in re.findall(r"silence_start: ([\d.]+)", out.stderr)]
    ends = [float(x) for x in re.findall(r"silence_end: ([\d.]+)", out.stderr)]
    gaps = sorted(zip(starts, ends, strict=False), key=lambda g: g[1] - g[0], reverse=True)[: n_parts - 1]
    if len(gaps) < n_parts - 1:
        sys.exit(f"video_kit: {path.name} has {len(gaps) + 1} pieces between pauses, {n_parts} voice-over lines expected")
    cuts = [0.0] + sorted((a + b) / 2 for a, b in gaps) + [probe(path)["duration"]]
    parts = []
    for i in range(n_parts):
        p = work / f"vo_part_{i + 1:02d}.wav"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(path), "-ss", f"{cuts[i]:.3f}", "-to", f"{cuts[i + 1]:.3f}",
                        "-af", "silenceremove=start_periods=1:start_threshold=-40dB,areverse,"
                        "silenceremove=start_periods=1:start_threshold=-40dB,areverse",
                        "-ar", "48000", "-ac", "2", str(p)], check=True)  # fmt: skip
        parts.append(p)
    return parts


def match_inbox(shots: list[dict], work: Path) -> tuple[dict[str, Path], dict[str, Path]]:
    files = sorted(p for p in INBOX.glob("*") if p.is_file() and not p.name.startswith("."))
    desk_ids = [s["id"] for s in shots if s["kind"] == "desk"]
    vo_ids = [s["id"] for s in shots if s["kind"] in VO_KINDS and s.get("say")]
    clips: dict[str, Path] = {}
    vos: dict[str, Path] = {}
    loose_v, loose_a = [], []
    for f in files:
        info = probe(f)
        if not info:
            continue
        stem = f.stem.upper().removeprefix("VO_").removeprefix("VO-")
        if info["video"] and stem in desk_ids:
            clips[stem] = f
        elif stem in vo_ids and (info["audio"] or info["video"]):
            vos[stem] = f
        elif info["video"]:
            loose_v.append((info["created"], f))
        elif info["audio"]:
            loose_a.append((info["created"], f))
    for sid, (_, f) in zip([i for i in desk_ids if i not in clips], sorted(loose_v), strict=False):
        clips[sid] = f
    free_vo = [i for i in vo_ids if i not in vos]
    loose_a.sort()
    if len(loose_a) == 1 and len(free_vo) > 1:
        loose_a = [(None, p) for p in split_long_vo(loose_a[0][1], len(free_vo), work)]
    for sid, (_, f) in zip(free_vo, loose_a, strict=False):
        vos[sid] = f
    return clips, vos


def cmd_plan(placeholders: bool) -> None:
    n = numbers()
    shots, _ = load(n)
    WORK.mkdir(parents=True, exist_ok=True)
    pieces = WORK / "pieces"
    if pieces.exists():
        shutil.rmtree(pieces)
    pieces.mkdir()
    clips, vos = ({}, {}) if placeholders else match_inbox(shots, WORK)
    rows = []
    for i, s in enumerate(shots, 1):
        sid, dur = s["id"], float(s["seconds"])
        video, is_image, zoom, audio, own_audio = "", 1, 0, "-", 0
        if s["kind"] == "card":
            video = str(WORK / f"card_{sid}.png")
            draw_card(s["card"], Path(video))
        elif s["kind"] == "desk":
            if sid in clips:
                info = probe(clips[sid])
                video, is_image, own_audio, dur = str(clips[sid]), 0, int(info["audio"]), info["duration"]
            else:
                video = str(WORK / f"slate_{sid}.png")
                draw_card({"title": f"{sid}: the founder at the desk", "subtitle": s.get("framing", ""),
                           "foot": s.get("framing", "")}, Path(video), slate="PLACEHOLDER")  # fmt: skip
        else:
            src = ROOT / s["src"]
            seg = probe(src) if src.is_file() and src.suffix.lower() in VIDEO_EXT else {}
            if seg.get("duration", 0) > 0.5:
                video, is_image = str(src), 0
                if seg["duration"] > dur + 0.5:  # never cut a recorded segment short
                    print(f"plan: {sid} {src.name} runs {seg['duration']:.1f} s, longer than its {dur:.0f} s slot; using it all")
                    dur = seg["duration"]
            elif src.is_file() and src.suffix.lower() not in VIDEO_EXT:
                video, zoom = str(src), 1
            elif s.get("fallback") and (ROOT / s["fallback"]).is_file():
                video, zoom = str(ROOT / s["fallback"]), 1
            else:
                video = str(WORK / f"slate_{sid}.png")
                draw_card({"title": f"{sid}: {Path(s['src']).name}",
                           "subtitle": "Not recorded yet. " + s.get("shows", "")}, Path(video), slate="PLACEHOLDER")  # fmt: skip
        if sid in vos:
            audio = str(vos[sid])
            dur = max(dur, probe(vos[sid])["duration"] + 0.6)  # a long voice-over stretches the shot
        s["final_seconds"] = round(dur, 3)
        rows.append([f"{i:02d}", sid, s["kind"], video, str(is_image), str(zoom), audio, str(own_audio), f"{dur:.3f}"])
    (WORK / "plan.tsv").write_text("\n".join("\t".join(r) for r in rows) + "\n", encoding="utf-8")
    events = caption_events(shots, timecodes(shots, "final_seconds"), "final_seconds")
    write_srt(events, WORK / "captions.srt")
    write_ass(events, WORK / "captions.ass")
    total = timecodes(shots, "final_seconds")[-1]
    used = {**{k: v.name for k, v in clips.items()}, **{k: v.name for k, v in vos.items()}}
    print(f"plan: {len(rows)} pieces, {mmss(total)} ({total:.1f} s); founder files used: "
          + (", ".join(f"{k}={v}" for k, v in used.items()) or "none (placeholders)"))  # fmt: skip


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["docs", "plan"])
    ap.add_argument("--placeholders", action="store_true", help="plan: ignore video/inbox, use slates")
    a = ap.parse_args()
    if a.command == "docs":
        cmd_docs()
    else:
        cmd_plan(a.placeholders)


if __name__ == "__main__":
    main()
